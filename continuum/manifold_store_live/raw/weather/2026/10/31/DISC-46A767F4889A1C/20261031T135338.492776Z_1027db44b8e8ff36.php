<pre><div style="line-height:130%;font-family:verdana;font-size:1em;">Short Range Forecast Discussion
NWS Weather Prediction Center College Park MD
400 AM EDT Sat Oct 31 2026

Valid 12Z Sat Oct 31 2026 - 12Z Mon Nov 02 2026

...Heavy rain threat renews over southern California and Desert
Southwest this evening; impactful flash flooding expected in the
Great Basin and Four Corners Sunday...

...Locally heavy rainfall shifting gradually eastward from the
southern Plains to the Gulf Coast states this weekend...

...Low pressure area brings unsettled weather to the Central U.S.
on Monday...

An increasingly wet weather pattern is in store across the
Southwest this weekend and the Gulf Coast states as a dry weather
pattern continues over much of the eastern U.S. The impetus for the
wet weather pattern in the West is a broad upper-level trough
lifting sub-tropical moisture into the Southwest, and scattered
showers and thunderstorms will persist throughout today. Meanwhile,
a low pressure wave now developing between Hawaii and Baja
California is heading toward southern California. The low pressure
wave approaching the Pacific coast will deliver a trick for the
Southwest by late Halloween night as the second wave of rain
reaches southern California. Rainfall will quickly expand north and
northeastwards across the Southwest, Great Basin, and Four
Corners. Rainfall amounts upwards of 2-4" along upslope facing
terrain in these regions could lead to numerous instances of flash
flooding tomorrow as it overlaps with widespread saturated soils.
By Monday, a lee-side cyclone is expected to spin up in the Central
High Plains ahead of the Pacific system. Much of the Heartland will
wake up to wet weather to kick off the work week with isolated
heavy rainfall possible. Portions of the Central Rockies could see
heavy snow on the back side of this system as well.

Meanwhile, another corridor of moderate rainfall across the
southern Plains will gradually shift eastward to reach the Gulf
Coast states this weekend. The great threat of heavy rainfall will
be associated with heavier showers and thunderstorms near the Gulf
Coast region. These showers and storms will continue to shift
slowly east to reach the Florida Panhandle and northward up the
Mississippi Valley by Sunday morning. Lingering thunderstorms near
the tail end of an old front will maintain isolated flash flooding
potential for South Florida into the weekend. In contrast, a high
pressure system will provide dry weather or much of the eastern
U.S. into the weekend will colder than normal conditions in New
England but milder than normal to the south.

Over the Sierra and Great Basin, snowfall will expand late
tomorrow and Sunday as the West Coast upper-low and the approaching
Pacific system interact. Over a foot of snowfall could result in
the peaks of the terrain through late Sunday.


