<pre><div style="line-height:130%;font-family:verdana;font-size:1em;">Short Range Forecast Discussion
NWS Weather Prediction Center College Park MD
300 PM EST Sun Nov 1 2026

Valid 00Z Mon Nov 02 2026 - 00Z Wed Nov 04 2026

...Impactful flash flooding expected in the Great Basin and Four
Corners through tonight...

...Heavy rainfall threat continues along the east coast of Florida
through Monday...

...Intensifying low pressure system brings gusty winds, locally
heavy rain, and severe weather to the Great Plains...

A widespread moderate to heavy rainfall event is currently in full
swing across the Four Corners region this Sunday afternoon as a
moisture-ladden low pressure system from the subtropical Pacific
interacts with a deepening upper-level trough moving further inland
into the southwestern U.S. WPC continues to highlight a very broad
slight risk of flash flooding area for much of the Four Corners
states through tonight, together with a moderate risk from central
Arizona to southwestern Utah, and just to the north and east of the
Four Corners. This merger will pick up its eastward motion,
tapering the heavy precipitation from west to east across the Four
Corners region through tonight. High-elevation wet snow can also
be expected especially later tonight over the northern and central
Rockies as far south as the San Juan Mountains, where a Winter
Storm Warning and a handful of Winter Weather Advisories are in
effect. In addition, the Storm Prediction Center (SPC) is
highlighting a slight risk of severe thunderstorms from the
southern Rockies to the southern High Plains through tonight into
early Monday morning.

Monday will feature a rather strong and deep cyclone spinning up
rapidly and expanding across the northern Great Plains. Much of
the Northern Plains will wake up to increasing winds, showers, and
embedded thunderstorms to kick off the work week. The Central and
Southern Plains can expect to see thunderstorms potentially turn
severe later on Monday with locally heavy rainfall possible. SPC is
highlighting portions of the Central and Southern Plains for a
slight risk of severe thunderstorms Monday and Monday night. On
Tuesday, a sweeping cold front will shift the focus for unsettled
weather from the Plains into the Mid/Lower Mississippi Valley.

Meanwhile, showers and embedded thunderstorms enhanced by sustained
onshore flow from the Atlantic combined with weak upper-level
troughing arriving from the Gulf Coast have resulted in deep
convection and locally heavy rainfall for portions of south-central
Florida Panhandle today. Continued onshore flow from a large high
pressure system sliding off the East Coast will bring additional
heavy rainfall threat for portions of southern Florida Peninsula
on Monday with isolated to scattered flash flooding potential. In
contrast, the same high pressure system will maintain dry weather
for much of the eastern U.S. with colder than normal conditions in
New England but milder than normal to the south.

Kong/Asherman


